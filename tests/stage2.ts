import assert from "node:assert/strict";
import { PERSONALITY_RULES, PERSONALITY_V2 as cfg } from "../src/config/personality";
import { buildContribution, derivePersonality, resolveDominant, reviseContribution, type PersonalityState } from "../src/domain/personality";
import { migrateSnapshotV2toV3 } from "../src/domain/migrations";
import { createInitialSnapshot, applyGameEvent } from "../src/domain/rules";
import { createEmptyCompanion } from "../src/domain/companion";
import { validateSnapshot, validateSnapshotJson } from "../src/domain/schema";
import { createLocalStorageAdapter, SNAPSHOT_STORAGE_KEY } from "../src/lib/storage/localStorageAdapter";
import type { EmotionReading, SnapshotV2 } from "../src/domain/types";

async function main() {
const day = "2026-11-13";
const emotion = (label: EmotionReading["label"], intensity = 0.5): EmotionReading => ({ label, intensity, valence: .5, arousal: .5, dominance: .5, source: "manual", confidence: null });
const ctx = { now: 1, dayKey: day };
const confirm = (id: string, label: EmotionReading["label"]) => ({ type: "CONFIRM_ENTRY" as const, eventId: `e${id}`, entryId: id, text: `原文 ${id}`, emotion: emotion(label), analysis: null, analysisMeta: null });
let s = createInitialSnapshot();
s = applyGameEvent(s, confirm("1", "joy"), ctx).snapshot;
assert.equal(derivePersonality(s.personality).scores.cheerfulness, 53);
assert.equal(s.personality.dominantId, "cheerfulness");
assert.equal(applyGameEvent(s, confirm("1", "joy"), ctx).changed, false);
s = applyGameEvent(s, confirm("2", "joy"), ctx).snapshot;
assert.equal(s.personality.contributions["2"].deltas.cheerfulness, 1);
const other = s.personality.contributions["2"];
const correct = { type: "CORRECT_EMOTION" as const, eventId: "correct", entryId: "1", expectedEntryRevision: 0, emotion: emotion("sadness"), analysis: null, analysisMeta: null };
s = applyGameEvent(s, correct, { now: 2, dayKey: "2026-11-14" }).snapshot;
assert.deepEqual(s.personality.contributions["2"], other);
assert.equal(s.personality.contributions["1"].dayKey, day);
assert.equal(s.personality.contributions["1"].deltas.cheerfulness, -2);
const before = s.personality;
s = applyGameEvent(s, { type: "EDIT_ENTRY_TEXT", eventId: "edit", entryId: "1", expectedEntryRevision: 1, text: "保留原样的编辑" }, ctx).snapshot;
assert.deepEqual(s.personality, before);
const tied = { gentleness: 50, curiosity: 50, cheerfulness: 50, fearfulness: 50, low_mood: 50 };
assert.equal(resolveDominant(tied, null, cfg.dominantPriority), "gentleness");
assert.equal(resolveDominant(tied, "curiosity", cfg.dominantPriority), "curiosity");
assert.equal(resolveDominant({ ...tied, gentleness: 51 }, "curiosity", cfg.dominantPriority), "gentleness");
assert.equal(buildContribution(day, "joy", .34, 0, {}, cfg).deltas.cheerfulness, 2);
assert.equal(buildContribution(day, "joy", .35, 0, {}, cfg).deltas.cheerfulness, 3);
assert.equal(buildContribution(day, "calm", .7, 0, {}, cfg).deltas.gentleness, 2);
assert.equal(buildContribution(day, "calm", .71, 0, {}, cfg).deltas.gentleness, 3);
assert.equal(buildContribution(day, "anger", .34, 0, {}, cfg).deltas.curiosity, -1);
const sample = (v: number) => ({ dayKey: day, label: "joy" as const, entryRevision: 0, rulesVersion: "old", deltas: { ...tied, gentleness: v, curiosity: 0, cheerfulness: 0, fearfulness: 0, low_mood: 0 } });
for (const [v, label, expected] of [[6, "anger", -2], [6, "joy", 0], [-6, "joy", 1], [-6, "anger", 0]] as const) {
 const c = buildContribution(day, label, .5, 0, { a: sample(v) }, cfg); assert.equal(c.deltas.gentleness, expected);
}
const missing: PersonalityState = { ...s.personality, contributions: { ...s.personality.contributions, "1": { ...s.personality.contributions["1"], rulesVersion: "missing" } } };
assert.equal(reviseContribution(missing, "1", "joy", .5, 2), null);
assert.deepEqual(derivePersonality(missing).scores, derivePersonality(s.personality).scores);
const oldConfig = { ...cfg, rulesVersion: "old-test", dailyNetCap: 6 };
(PERSONALITY_RULES as Record<string, typeof cfg>)["old-test"] = oldConfig;
const legacyState = { ...s.personality, contributions: { ...s.personality.contributions, "1": { ...s.personality.contributions["1"], rulesVersion: "old-test" } } };
assert.equal(reviseContribution(legacyState, "1", "joy", .5, 2)?.contributions["1"].rulesVersion, "old-test");
const missingSnapshot = { ...s, personality: missing };
assert.equal(validateSnapshot(missingSnapshot).ok, true);
assert.equal(applyGameEvent(missingSnapshot, { ...correct, eventId: "missing-rule", expectedEntryRevision: 2 }, ctx).changed, false);
const oldSnapshot = { ...s, personality: legacyState };
assert.equal(validateSnapshot(oldSnapshot).ok, true);
const v2: SnapshotV2 = { schemaVersion: 2, revision: 4, character: { totalXp: 12, stage: 2, latestEntryId: s.entries[0].id, currentEmotion: s.entries[0].effectiveEmotion }, entries: s.entries, memories: s.memories, appliedEventIds: s.appliedEventIds, decorations: { ownedIds: [], equippedBySlot: {}, hiddenById: {} }, companion: createEmptyCompanion() };
const migrated = migrateSnapshotV2toV3(v2);
assert.deepEqual(migrated.entries, v2.entries); assert.deepEqual(migrated.memories, v2.memories); assert.deepEqual(migrated.legacy?.companion, v2.companion); assert.equal(migrated.legacy?.character?.totalXp, 12);
const oldCorrect = applyGameEvent(migrated, { ...correct, eventId: "old-correct", expectedEntryRevision: 2 }, ctx);
assert.equal(oldCorrect.changed, true); assert.deepEqual(oldCorrect.snapshot.personality, migrated.personality);
assert.equal(validateSnapshot(oldCorrect.snapshot).ok, true);
let raw: string | null = JSON.stringify(v2); let fail = false;
const fakeStorage = { getItem: () => raw, setItem: (_: string, value: string) => { if (fail) throw new Error("failed"); raw = value; } };
Object.defineProperty(globalThis, "window", { value: { localStorage: fakeStorage }, configurable: true });
const storage = createLocalStorageAdapter(); const loaded = await storage.load(); assert.equal(loaded.status, "ready");
assert.equal(JSON.parse(raw!).schemaVersion, 2);
if (loaded.status !== "ready") throw new Error("load failed");
const candidate = applyGameEvent(loaded.snapshot, confirm("new", "joy"), ctx).snapshot;
fail = true; assert.notEqual((await storage.save(candidate, 4)).status, "saved"); assert.equal(JSON.parse(raw!).schemaVersion, 2); assert.equal(loaded.snapshot.personality.contributions.new, undefined);
fail = false; assert.equal((await storage.save(candidate, 4)).status, "saved"); const reloaded = await storage.load();
assert.equal(reloaded.status, "ready"); if (reloaded.status === "ready") assert.deepEqual(reloaded.snapshot.personality, candidate.personality);
raw = '{"schemaVersion":99}'; assert.equal((await storage.load()).status, "unsupported-version"); assert.equal((await storage.save(candidate, 4)).status, "conflict"); assert.equal(raw, '{"schemaVersion":99}');
raw = "broken"; assert.equal((await storage.load()).status, "corrupt"); assert.equal(raw, "broken");
assert.equal(validateSnapshotJson(JSON.stringify(v2)).ok, true);
void SNAPSHOT_STORAGE_KEY;
console.log("阶段二领域、迁移和存储验证通过");
}
void main();
